export interface AgentEvalVars {
  question?: string;
  peerId?: string;
  presetId?: string;
  threadId?: string;
  memories?: Array<Partial<Memory> & Pick<Memory, 'type' | 'content'>>;
  messages?: Array<Partial<AgentMessageRecord> & Pick<AgentMessageRecord, 'message'>>;
  dialogPreset?: DialogPreset;
}

export interface AgentEvalOutput {
  /** Final assistant text response from `generateNode`. */
  answer: string;
  /** Intent classified by `understandNode`. */
  intent: string;
  /** Number of memories pulled by `retrieveNode`. */
  retrievedMemoriesCount: number;
  /** Number of chat messages pulled by `retrieveNode`. */
  retrievedMessagesCount: number;
  /** Execution trace / reasoning generated by `generateNode`. */
  thought?: string;
}

interface ProviderOptions {
  id?: string;
  config?: {
    model?: string;
    temperature?: number;
  };
}

/**
 * Lightweight fixture-backed Retriever for Promptfoo E2E graph evaluations.
 * Avoids browser IndexedDB dependencies while exercising the real
 * `understandNode -> retrieveNode -> generateNode` LangGraph pipeline.
 */
function createFixtureRetriever(vars: AgentEvalVars): Retriever {
  const now = Date.now();
  const seededMemories: Memory[] = (vars.memories ?? []).map((m, idx) => ({
    id: m.id ?? `eval-mem-${idx + 1}`,
    type: m.type,
    content: m.content,
    subjectId: m.subjectId,
    predicate: m.predicate,
    objectId: m.objectId,
    confidence: m.confidence ?? 0.95,
    importance: m.importance ?? 0.8,
    status: m.status ?? 'ACTIVE',
    createdAt: m.createdAt ?? now,
    updatedAt: m.updatedAt ?? now,
  }));

  const seededMessages: AgentMessageRecord[] = (vars.messages ?? []).map((msg, idx) => ({
    id: msg.id ?? `eval-msg-${idx + 1}`,
    peerId: msg.peerId ?? vars.peerId ?? 'peer-eval-1',
    fromId: msg.fromId ?? 'user-1',
    date: msg.date ?? now - idx * 60_000,
    message: msg.message,
    out: msg.out ?? false,
  }));

  const stub = {
    async getDialogPreset(peerId: string): Promise<DialogPreset | undefined> {
      if (vars.dialogPreset && (!vars.dialogPreset.peerId || vars.dialogPreset.peerId === peerId)) {
        return vars.dialogPreset;
      }
      return undefined;
    },

    async searchMessages(query: string, peerId?: string): Promise<AgentMessageRecord[]> {
      const lower = query.toLowerCase();
      return seededMessages.filter((m) => {
        if (peerId && m.peerId !== peerId) return false;
        // Match if any keyword (>3 chars) in the user query appears in the message, or fallback to all seeded messages for the peer
        const tokens = lower.split(/\W+/).filter((t) => t.length > 3);
        if (tokens.length === 0) return true;
        return tokens.some((token) => m.message.toLowerCase().includes(token));
      });
    },

    async getConversation(peerId: string, limit = 50): Promise<AgentMessageRecord[]> {
      return seededMessages
        .filter((m) => m.peerId === peerId)
        .sort((a, b) => b.date - a.date)
        .slice(0, limit);
    },

    async searchMemories(subjectId?: string, type?: Memory['type']): Promise<Memory[]> {
      return seededMemories.filter((m) => {
        if (subjectId && m.subjectId !== subjectId) return false;
        if (type && m.type !== type) return false;
        return m.status === 'ACTIVE';
      });
    },

    async searchMemoriesByText(query: string): Promise<Memory[]> {
      const lower = query.toLowerCase();
      const tokens = lower.split(/\W+/).filter((t) => t.length > 3);
      return seededMemories.filter((m) => {
        if (m.status !== 'ACTIVE') return false;
        if (tokens.length === 0) return true;
        return tokens.some((token) => m.content.toLowerCase().includes(token));
      });
    },

    async getPerson(_name: string): Promise<Entity | undefined> {
      return undefined;
    },
  };

  return stub as unknown as Retriever;
}

/**
 * Custom Promptfoo Provider that runs the full TeleGenie LangGraph agent
 * (`UNDERSTAND -> RETRIEVE -> GENERATE`).
 */
export default class TeleGenieGraphProvider {
  private readonly providerId: string;
  private readonly model: string;
  private readonly temperature: number;

  constructor(options: ProviderOptions = {}) {
    this.model = options.config?.model ?? 'gpt-4o';
    this.temperature = options.config?.temperature ?? 0;
    this.providerId = options.id ?? `telegenie-graph:${this.model}`;
  }

  id(): string {
    return this.providerId;
  }

  async callApi(
    prompt: string,
    context?: { vars?: AgentEvalVars },
  ): Promise<{ output: AgentEvalOutput; error?: string }> {
    const vars: AgentEvalVars = context?.vars ?? {};

    setModelConfig({
      model: this.model,
      temperature: this.temperature,
      apiKeys: {
        openai: process.env.OPENAI_API_KEY,
        anthropic: process.env.ANTHROPIC_API_KEY,
        google: process.env.GOOGLE_API_KEY,
      },
    });

    initNodes(createFixtureRetriever(vars));

    const graph = createGraph();
    const threadId = vars.threadId ?? `eval-thread-${Date.now()}`;

    try {
      const finalState = await graph.invoke(
        {
          messages: [new HumanMessage(prompt)],
          peerId: vars.peerId,
          presetId: vars.presetId,
          model: this.model,
          runId: `eval-run-${Date.now()}`,
        },
        {
          configurable: { thread_id: threadId },
        },
      );

      const lastMessage = finalState.messages[finalState.messages.length - 1];
      const answer = extractText(lastMessage?.content);

      return {
        output: {
          answer,
          intent: finalState.intent,
          retrievedMemoriesCount: finalState.retrievedMemories?.length ?? 0,
          retrievedMessagesCount: finalState.retrievedMessages?.length ?? 0,
          thought: finalState.thought,
        },
      };
    } catch (err) {
      return {
        output: {
          answer: '',
          intent: '',
          retrievedMemoriesCount: 0,
          retrievedMessagesCount: 0,
        },
        error: err instanceof Error ? err.message : String(err),
      };
    }
  }
}

